import { randomUUID } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";

/**
 * Agents push only through the approved managed push. Their shells get a global Git config that
 * includes the user's own global config and rewrites every push URL to a helper that does not
 * exist, so `git push` fails while fetch, commit and the rest of Git keep working.
 * An agent can still bypass it on purpose (an absolute pushurl, a different GIT_CONFIG_GLOBAL);
 * the post-turn push audit reports those.
 */
export const PUSH_GUARD_SCHEME = "role-workflow-approval-required";
const FILE = "push-guard.gitconfig";

function quoted(value: string) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/** The global files Git would read without the guard, in Git's own order. */
export function originalGlobalConfigs(env: Record<string, string | undefined>, guardFile: string) {
  const configured = env.GIT_CONFIG_GLOBAL;
  if (configured && path.resolve(configured) !== path.resolve(guardFile)) return [configured];
  if (configured) return [];
  const home = env.HOME || homedir();
  const xdg = env.XDG_CONFIG_HOME || path.join(home, ".config");
  return [path.join(xdg, "git", "config"), path.join(home, ".gitconfig")];
}

export function pushGuardConfig(includes: readonly string[]) {
  return [
    "# Generated by role-workflow. Push only through the approved managed push (/push).",
    "[include]",
    ...includes.map((file) => `\tpath = ${quoted(file)}`),
    `[url ${quoted(`${PUSH_GUARD_SCHEME}://use-the-push-approval-screen/`)}]`,
    "\tpushInsteadOf =",
    "",
  ].join("\n");
}

/** Writes the guard file when its content changed and returns the env override for an agent. */
export async function pushGuardEnv(
  directory: string,
  requestEnv: Record<string, string>,
  processEnv: Record<string, string | undefined> = process.env,
): Promise<Record<string, string>> {
  const file = path.join(directory, FILE);
  const content = pushGuardConfig(originalGlobalConfigs({ ...processEnv, ...requestEnv }, file));
  const current = await readFile(file, "utf8").catch(() => null);
  if (current !== content) {
    await mkdir(directory, { recursive: true });
    // Sessions open concurrently in one plugin process; each write needs its own temporary file.
    const temporary = `${file}.${process.pid}.${randomUUID()}.tmp`;
    await writeFile(temporary, content, { mode: 0o600 });
    await rename(temporary, file);
  }
  return { ...requestEnv, GIT_CONFIG_GLOBAL: file };
}

const GIT_OPTIONS_WITH_VALUE = new Set(["-C", "-c", "--git-dir", "--work-tree", "--namespace", "--exec-path", "--config-env"]);

/** True when a shell command runs `git … push`. Quoted text is ignored, so a commit message saying "push" is not a push. */
export function runsGitPush(command: string) {
  // A quoted argument stays one placeholder word, so `git -C "a b" push` still reads as a push.
  const unquoted = command.replace(/'[^']*'|"(?:\\.|[^"\\])*"/g, " _quoted_ ");
  for (const segment of unquoted.split(/[;&|\n()`]|\$\(/)) {
    const words = segment.trim().split(/\s+/).filter(Boolean);
    for (let i = 0; i < words.length; i++) {
      if (words[i] !== "git" && !words[i].endsWith("/git")) continue;
      let j = i + 1;
      while (j < words.length && words[j].startsWith("-")) {
        j += GIT_OPTIONS_WITH_VALUE.has(words[j]) ? 2 : 1;
      }
      if (words[j] === "push") return true;
    }
  }
  return false;
}

/** Shell commands carried by a permission request (Claude Bash, Codex exec). */
export function permissionCommands(input: unknown): string[] {
  if (!input || typeof input !== "object") return [];
  const record = input as Record<string, unknown>;
  const commands: string[] = [];
  for (const key of ["command", "cmd"]) {
    const value = record[key];
    if (typeof value === "string") commands.push(value);
    if (Array.isArray(value) && value.every((part) => typeof part === "string"))
      commands.push(value.join(" "));
  }
  return commands;
}

